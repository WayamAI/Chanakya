"""The Wayam knowledge layer: one place that answers "what do we know and what may we say about accelerator X?".

It gathers, per accelerator, everything already stored with provenance: the catalogue record (summary, problems,
industries, buyer roles, limitations, evidence links), customer needs quoted from the catalogue, the ICP, the buyer
personas and their review status, the proof registry (claims allowed and claims forbidden), the approved outreach
wording, the signal phrases the discovery sweeps look for, current demand, and the Lakshya research on the product
(parts, competitors). Agents and the UI read it through `accelerator()` / `catalogue()`; nothing here is generated by
a model, so a draft or a brief built from it cannot contain a capability, case study or claim Wayam has not recorded.

`gaps` in each record lists what is missing (no ICP, no approved persona, no registered proof, no approved angle), so
the team can see why an accelerator cannot yet be searched for or backed with proof.
"""
from __future__ import annotations

import json


def _j(v, default):
    try:
        out = json.loads(v) if v else default
        return default if out is None else out
    except (TypeError, ValueError):
        return default


def accelerator(con, product_id: str) -> dict | None:
    from chanakya.intel import content as C
    from chanakya.intel import lakshya as LK
    from chanakya.intel.sources import jobs_public, tenders_uk
    from chanakya.intel.voice import accelerator_url
    r = con.execute("SELECT * FROM products WHERE id=?", (product_id,)).fetchone()
    if r is None:
        return None
    needs = [n for n in _j(r["needs_json"], []) if isinstance(n, dict)]
    icp = con.execute("SELECT id, icp_json, created_at FROM icps WHERE product_id=? ORDER BY id DESC LIMIT 1",
                      (product_id,)).fetchone()
    personas = [{"persona": p["persona"], "status": p["status"], "titles": _j(p["titles_json"], []),
                 "seniorities": _j(p["seniorities_json"], [])}
                for p in con.execute("SELECT * FROM persona_role_mappings WHERE product_id=? ORDER BY id",
                                     (product_id,))]
    proof = [dict(p) for p in con.execute("SELECT claim, allowed, note FROM accelerator_proof WHERE product_id=? ORDER "
                                          "BY allowed DESC, id", (product_id,))]
    try:
        angle = C.accelerator_angle(product_id)
        wording = {"what_we_do": C.paragraph("what_we_do", accelerator=r["name"]), "angle": angle,
                   "ask": C.paragraph("ask"), "signature": C.signature(None)}
    except Exception as e:  # noqa: BLE001 - a broken content file is reported, the rest of the record still loads
        angle, wording = None, {"error": f"{type(e).__name__}: {e}"[:200]}
    lak = LK.for_product(con, product_id)
    demand = con.execute(
        "SELECT COUNT(DISTINCT s.id) signals, COUNT(DISTINCT s.company_id) companies, MAX(f.score) best FROM "
        "signal_fits f JOIN signals s ON s.id=f.signal_id WHERE f.product_id=? AND COALESCE(s.verification_status,'')"
        "!='rejected'", (product_id,)).fetchone()
    allowed = [p["claim"] for p in proof if p["allowed"]]
    gaps = []
    if icp is None:
        gaps.append("no ICP: a Clay company search cannot be built; discovery relies on signals")
    if not any(p["status"] == "approved" for p in personas):
        gaps.append("no approved buyer persona: contact searches and bottom-up queries are not planned")
    if not allowed:
        gaps.append("no registered proof: drafts must not claim any result; proof fit scores 0")
    if not angle:
        gaps.append("no approved outreach angle in the Wayam content file")
    if not needs:
        gaps.append("no customer needs extracted from the catalogue summary")
    return {
        "id": r["id"], "name": r["name"], "status": r["status"], "url": accelerator_url(r["id"]),
        "summary": r["summary"], "problems_solved": _j(r["problems_solved_json"], []),
        "capabilities": [n.get("quote") for n in needs], "needs": needs,
        "target_industries": _j(r["target_industries_json"], []), "buyer_roles": _j(r["buyer_roles_json"], []),
        "integrations": _j(r["integrations_json"], []), "deployment": r["deployment"],
        "differentiators": _j(r["differentiators_json"], []), "limitations": _j(r["caveats_json"], []),
        "evidence_links": _j(r["evidence_json"], []),
        "catalogue": {"version": r["catalogue_version"], "source": r["source_path"], "sha256": r["source_sha256"],
                      "verification": r["verification"], "imported_at": r["imported_at"]},
        "icp": {"id": icp["id"], "created_at": icp["created_at"], **_j(icp["icp_json"], {})} if icp else None,
        "personas": personas,
        "proof": {"may_claim": allowed, "must_not_claim": [p["claim"] for p in proof if not p["allowed"]],
                  "notes": [p["note"] for p in proof if p["note"]]},
        "approved_wording": wording,
        "signal_phrases": {"tenders": tenders_uk.DEFAULT_KEYWORDS.get(product_id, []),
                           "hiring": jobs_public.DEFAULT_KEYWORDS.get(product_id, [])},
        "demand": {"signals": demand["signals"], "companies": demand["companies"], "best_fit": demand["best"],
                   "opportunities": con.execute("SELECT COUNT(*) FROM opportunities WHERE product_id=?",
                                                (product_id,)).fetchone()[0]},
        "lakshya": {"parts": [x for x in lak if x["kind"] == "setu_part"],
                    "competitors": [x for x in lak if x["kind"] == "competitor"]},
        "gaps": gaps,
        "rules": ["State only capabilities listed here.", "Claim only results under proof.may_claim.",
                  "Never claim anything under proof.must_not_claim.", "Use approved_wording for what Wayam does."],
    }


def catalogue(con) -> list[dict]:
    """Every accelerator, compact: readiness for search, proof and outreach at a glance."""
    out = []
    for (pid,) in con.execute("SELECT id FROM products ORDER BY name").fetchall():
        a = accelerator(con, pid)
        out.append({"id": a["id"], "name": a["name"], "status": a["status"], "summary": a["summary"],
                    "has_icp": a["icp"] is not None,
                    "approved_personas": sum(1 for p in a["personas"] if p["status"] == "approved"),
                    "proof_points": len(a["proof"]["may_claim"]), "has_angle": bool(a["approved_wording"].get("angle")),
                    "signal_phrases": len(a["signal_phrases"]["tenders"]) + len(a["signal_phrases"]["hiring"]),
                    "demand": a["demand"], "gaps": a["gaps"]})
    return out


def search(con, q: str) -> list[dict]:
    """Accelerators whose recorded text mentions `q` (summary, needs, problems, industries, roles), with the matching
    lines, so an agent can ask "which accelerator covers X?" from stored knowledge only."""
    ql = (q or "").strip().lower()
    if not ql:
        return []
    hits = []
    for (pid,) in con.execute("SELECT id FROM products ORDER BY name").fetchall():
        a = accelerator(con, pid)
        lines = [a["summary"] or "", *[str(x) for x in a["problems_solved"]], *[str(x) for x in a["capabilities"] if x],
                 *[str(x) for x in a["target_industries"]], *[str(x) for x in a["buyer_roles"]]]
        m = [ln for ln in lines if ql in ln.lower()]
        if m or ql in a["name"].lower():
            hits.append({"id": pid, "name": a["name"], "matches": m[:5], "proof_points": len(a["proof"]["may_claim"]),
                         "gaps": a["gaps"]})
    return hits
